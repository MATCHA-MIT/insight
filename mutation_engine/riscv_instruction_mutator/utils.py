def int_to_little_endian_hex(n):
    # Convert the integer to a bytes object in little-endian format
    byte_representation = n.to_bytes((n.bit_length() + 7) // 8, byteorder='little')

    # Convert the bytes object to a hexadecimal string
    hex_string = byte_representation.hex()

    return hex_string

def get_instruction_dict_from_bytestring(code):
    # Disassemble the instructions
    dis = disassembler.Disassembler()
    instructions = {}

    for i in range(0, len(code), 4):
        instruction = int.from_bytes(code[i:i+4], "little")
        mnemonics = dis.disassemble(instruction)
        if mnemonics:
            instructions[instruction] = {"mnemonics": mnemonics, "index": (i+1) // 4}
            logger.debug(f"Index {(i+1) // 4}: {mnemonics}")
        else:
            instructions[instruction] = {"mnemonics": None, "index": (i+1) // 4}
    return instructions

def to_twos_complement(value, bits):
    # Ensure the value fits within the specified number of bits
    if value >= 2**(bits - 1) or value < -2**(bits - 1):
        raise ValueError(f"Value {value} is out of range for {bits}-bit two's complement representation")

    # Handle positive numbers and zero
    if value >= 0:
        return format(value, '0{}b'.format(bits))

    # Handle negative numbers
    return format((1 << bits) + value, '0{}b'.format(bits))

def required_bits_for_negative_number(number):
    if number >= 0:
        raise ValueError("The input number must be negative.")

    # Calculate the absolute value of the number
    abs_number = abs(number)

    # Find the number of bits required
    n = math.ceil(math.log2(abs_number)) + 1

    return n

def value_to_binary_string(value, bit_length, clamp=False):
    """
    Convert a value to a binary string
    We guess whether the value is stored in two's complement or not
    Not ideal, but I am not sure what could a better solution right now.
    :clamp: If clamp is true, and the value is "too high", we will just
    clamp to the right value
    """
    if value >= 2**(bit_length) and clamp: #Max range 2**(bit_lenght)-1 -> Therefore we clamp
        bin_string = format(value, '{}b'.format(int(math.log(value,2))))
        return bin_string[-bit_length:]
    if value < -2**(bit_length-1):
        required_bits = required_bits_for_negative_number(value)
        binary_string = to_twos_complement(int(value), required_bits)
        return binary_string[:bit_length]
    if value >= 2**(bit_length-1) and value < 2**(bit_length):
        return format(value, '{}b'.format(bit_length))
    if bit_length > 1:
        binary_string = to_twos_complement(int(value), bit_length)
    else:
        binary_string = format(int(value), '{}b'.format(bit_length))
    return binary_string


