def generate_riscv_load_immediate_program(out_register_number, immediate):
    """
    Generates a RISC-V assembly program to write a constant immediate into a register out_register_number.

    Args:
        N (int): The constant value to write into the register.

    Returns:
        str: RISC-V assembly code as a string.
    """
    # Initialize the program as a list of lines
    program_lines = [
        "# RISC-V Assembly Program to load a constant into x1",
        "# Generated by Python",
        "",
        ".section .text",
        ".globl _start",
        "_start:",
        f"    li x{out_register_number}, {immediate}       # Load immediate value {immediate} into register x{out_register_number}",
        "",
        "    # End of program",
        "    nop              # No operation",
        ""
    ]

    # Join the lines with newlines to form the full program
    return "\n".join(program_lines)

