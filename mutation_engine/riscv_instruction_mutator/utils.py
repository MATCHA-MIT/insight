def int_to_bits(n: int, width: int) -> str:
    #print("Binary", bin(n))
    return bin(n)[2:].zfill(width)

def bits_to_int(bits: str) -> int:
    """
    Convert a binary string to an integer.
    :param bits: A string representing a binary number (e.g., '1101').
    :return: The integer value of the binary string.
    """
    return int(bits, 2) if bits else 0  # Handle empty string case

