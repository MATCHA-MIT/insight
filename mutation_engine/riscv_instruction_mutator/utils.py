def _load_instruction_types()-> list[instruction_type.InstructionType]:
    instructions = []
    with open(get_relative_path('../riscv-opcodes/instr_dict.yaml'), 'r') as f:
        instr_dict = yaml.safe_load(f)

    for instr in instr_dict:
        instructions.append( 
            instruction_type.InstructionType(
                instr,
                instr_dict[instr]['extension'],
                int(instr_dict[instr]['mask'], 16),
                int(instr_dict[instr]['match'], 16),
                instr_dict[instr]['variable_fields']
            )
        )
    return instructions

def set_operand(instr_bytes, mutated_operand_val, beg, end):
    mask = 0
    for i in range(int(end), int(beg)+1):
        mask = mask | 1 << i

    mutated_instr = instr_bytes & ~mask
    #mutated_instr = mutated_instr | (mutated_operand_val << int(end))
    #Applying Mutated Operand: The mutated_operand_val is shifted to the correct position and applied to the instruction bytes.
    #The mutated_operand_val is first masked to ensure it fits within the specified bit range (beg - end + 1 bits).
    mutated_instr = mutated_instr | ((mutated_operand_val & ((1 << (int(beg) - int(end) + 1)) - 1)) << int(end))
    return mutated_instr

